def _png(ancho: int, alto: int, pixeles: bytearray) -> bytes:
    """Codifica un buffer en escala de grises de 8 bits como PNG."""
    filas = bytearray()
    for y in range(alto):
        filas.append(0)  # filtro None
        filas.extend(pixeles[y * ancho : (y + 1) * ancho])
    comprimido = zlib.compress(bytes(filas), 9)

    def chunk(tipo: bytes, datos: bytes) -> bytes:
        c = tipo + datos
        return struct.pack(">I", len(datos)) + c + struct.pack(">I", zlib.crc32(c))

    cabecera = struct.pack(">IIBBBBB", ancho, alto, 8, 0, 0, 0, 0)  # 8 bits, grises
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", cabecera)
            + chunk(b"IDAT", comprimido) + chunk(b"IEND", b""))


def png_con_texto(lineas: list[str], escala: int = 3, margen: int = 6) -> bytes:
    """Renderiza líneas de texto (mayúsculas) a un PNG negro sobre blanco."""
    lineas = [ln.upper() for ln in lineas]
    max_cols = max((len(ln) for ln in lineas), default=1)
    cw, ch = 6, 8  # celda con espaciado (5x7 + 1 px)
    ancho = margen * 2 + max_cols * cw * escala
    alto = margen * 2 + len(lineas) * ch * escala
    pix = bytearray([255]) * (ancho * alto)  # fondo blanco

    def set_pixel(x: int, y: int):
        if 0 <= x < ancho and 0 <= y < alto:
            pix[y * ancho + x] = 0  # negro

    for fila, texto in enumerate(lineas):
        for col, ch_ in enumerate(texto):
            glifo = _FUENTE.get(ch_, _FUENTE[" "])
            bx = margen + col * cw * escala
            by = margen + fila * ch * escala
            for ry, bits in enumerate(glifo):
                for rx in range(5):
                    if bits & (1 << (4 - rx)):
                        for sy in range(escala):
                            for sx in range(escala):
                                set_pixel(bx + rx * escala + sx, by + ry * escala + sy)
    return _png(ancho, alto, pix)


