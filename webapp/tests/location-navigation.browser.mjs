// Run with the same PLAYWRIGHT_MODULE / ZMD_QA_ORIGIN options as location-editor.browser.mjs.
import assert from 'node:assert/strict';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.ZMD_QA_ORIGIN || 'http://127.0.0.1:4315';
const browser = await chromium.launch({headless: true});
const context = await browser.newContext();
await context.route('**/*', route => route.request().url().startsWith(origin) ? route.continue() : route.abort());
const page = await context.newPage();
try {
  await page.goto(origin);
  await page.locator('#open-run').click();
  await page.locator('.run-synthetic').evaluate(el => { el.open = true; });
  await page.locator('#use-synthetic').click();
  await page.locator('#run-policy').selectOption('standard');
  await page.locator('#run-capacity').fill('12');
  await page.locator('#run-seconds').fill('3');
  await page.locator('#edit-locations').click();
  await page.locator('#location-node').selectOption('1');
  await page.locator('#location-latitude').fill('-33.4507');
  await page.locator('#confirm-locations').click();
  await page.locator('#close-run').click();
  await page.goto(`${origin}/plan.html`);
  await page.locator('#open-run').click();
  assert.equal(await page.locator('#edit-locations').isEnabled(), true, 'A confirmed draft must survive navigation before its first run.');
  assert.equal(await page.locator('#run-capacity').inputValue(), '12');
  assert.equal(await page.locator('#run-seconds').inputValue(), '3');
  assert.equal(await page.locator('#export-instance').isDisabled(), true);
  await page.locator('#edit-locations').click();
  await page.locator('#location-node').selectOption('1');
  assert.equal(await page.locator('#location-latitude').inputValue(), '-33.4507');
  await page.locator('#cancel-locations').click();
  await Promise.all([page.waitForEvent('load', {timeout: 180000}), page.locator('#solve-run').click()]);
  await page.waitForFunction(() => document.querySelector('#run-source')?.textContent.includes('Resultado del motor'));
  assert.equal(await page.locator('#run-dialog').isVisible(), true);
  await page.locator('#show-config').click();
  await page.locator('#edit-locations').click();
  await page.locator('#location-node').selectOption('1');
  await page.locator('#location-latitude').fill('-33.4509');
  await page.locator('#confirm-locations').click();
  await page.locator('#run-reserve').fill('1.5');
  await page.locator('#run-seconds').fill('4');
  await page.locator('#close-run').click();
  await page.goto(origin);
  await page.locator('#open-run').click();
  assert.equal(await page.locator('#run-reserve').inputValue(), '1.5');
  assert.equal(await page.locator('#run-seconds').inputValue(), '4');
  assert.equal(await page.locator('#export-instance').isDisabled(), true);
  await page.locator('#edit-locations').click();
  await page.locator('#location-node').selectOption('1');
  assert.equal(await page.locator('#location-latitude').inputValue(), '-33.4509');
  console.log('PASS: navegación antes del primer cálculo y con resultado anterior conserva coordenadas, parámetros, presupuesto e invalidez de preparación.');
  await page.locator('#cancel-locations').click();
  await page.evaluate(() => {
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function(key, value) {
      if (key === 'zmd.webapp.location-draft.v1') throw new DOMException('Quota exceeded', 'QuotaExceededError');
      return original.call(this, key, value);
    };
  });
  await page.locator('#edit-locations').click();
  await page.locator('#location-node').selectOption('1');
  await page.locator('#location-latitude').fill('-33.4512');
  await page.locator('#confirm-locations').click();
  assert.match(await page.locator('#run-message').textContent(), /no pudo conservar el borrador/);
  await page.locator('#close-run').click();
  await page.goto(`${origin}/plan.html`);
  await page.locator('main[aria-busy="false"]').waitFor();
  await page.locator('#open-run').click();
  assert.equal(await page.locator('#edit-locations').isDisabled(), true);
  assert.equal(await page.locator('#export-instance').isDisabled(), true);
  assert.match(await page.locator('#run-message').textContent(), /entrada pendiente no está disponible/);
  console.log('PASS: cuota agotada se informa y la navegación no reemplaza el borrador perdido con ubicaciones anteriores.');
} finally { await browser.close(); }
