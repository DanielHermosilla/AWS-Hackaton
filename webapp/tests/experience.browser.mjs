// Optional ZMD_SOLVED_FIXTURE is a captured real /solve response.
// Its GET transport is replayed for UI checks; this does not test live solving.
// Set PLAYWRIGHT_MODULE, ZMD_QA_ORIGIN and ZMD_QA_OUTPUT as needed.
import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin=process.env.ZMD_QA_ORIGIN || 'http://127.0.0.1:4335';
const output=process.env.ZMD_QA_OUTPUT || '.local/experience-qa';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:800}});
await context.route('**/*', route=>route.request().url().startsWith(origin)?route.continue():route.abort());
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const results=[];
const note=text=>{results.push(text);console.log('PASS',text);};
async function ready(path='') {await page.goto(origin+path);await page.waitForSelector('main[aria-busy="false"]');}
await ready('/');
await page.locator('#theme-toggle').click();
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
await ready('/plan.html');
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
await page.reload();await page.waitForSelector('main[aria-busy="false"]');
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
await ready('/');
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
await page.goto(origin+'/salida.html');
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
note('El tema oscuro se conserva al navegar Inicio → Plan → recarga → Inicio → salida.');
await ready('/');
await page.locator('.data-note summary').click();
await page.locator('#home-main').evaluate(el=>el.scrollTop=el.scrollHeight);
const home=await page.evaluate(()=>{const m=document.querySelector('#home-main'),b=document.querySelector('.data-note').getBoundingClientRect();return{scroll:m.scrollTop,max:m.scrollHeight-m.clientHeight,bottom:b.bottom,viewport:innerHeight,body:document.body.getBoundingClientRect().top,text:document.querySelector('.data-note').innerText};});
assert(home.scroll>0);assert(home.bottom<=home.viewport);assert.equal(home.body,0);assert(home.text.split(/\s+/).length<50);
await page.screenshot({animations:'disabled',path:output+'/home-dark-desktop.png'});
note('Sobre estos indicadores cabe en el scroll sin desplazar la cabecera y su explicación es breve.');
await page.setViewportSize({width:390,height:844});
await ready('/');await page.locator('.data-note summary').click();
await page.locator('.data-note').scrollIntoViewIfNeeded();
assert(await page.locator('.data-note [data-motion-detail]').isVisible());
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({animations:'disabled',path:output+'/home-dark-mobile.png'});
note('Inicio móvil mantiene tema, disclosure accesible y no desborda horizontalmente.');
assert(!await page.locator('body').innerText().then(text=>/Daniel|Lucas|Diego/.test(text)));
note('La interfaz visible usa un perfil local genérico.');
const fixtureFile=process.env.ZMD_SOLVED_FIXTURE;
if (fixtureFile) {
 const envelope=JSON.parse(await readFile(fixtureFile,'utf8'));
 const runId=envelope.result.run_id;
 await context.route('**/solve?*',route=>route.fulfill({json:envelope}));
 await page.evaluate(({runId})=>sessionStorage.setItem('zmd.webapp.execution.v1',JSON.stringify({runId,status:'complete',stale:false})),{runId});
 await page.setViewportSize({width:1440,height:900});
 await ready('/plan.html');
 await page.locator('#stops-tab').click();
 await page.waitForFunction(()=>document.querySelector('#map').dataset.mapReady==='true');
 const strings=await page.locator('.stop-row').allInnerTexts();
 assert(strings.length>=4);assert(!strings.some(value=>/BASE#fin|Visita\|ñ|witness_and/.test(value)));
 assert(strings.some(value=>value.includes('Salida del depósito')));
 assert(strings.some(value=>value.includes('Regreso al depósito')));
 assert.equal(await page.locator('.map-status').getByText(/Aproximación por distancia/).count(),1);
 await page.screenshot({animations:'disabled',path:output+'/synthetic-plan-desktop.png'});
 note('Respuesta real: paradas con nombres legibles, salida/regreso al depósito y rótulo de aproximación.');
 await page.locator('.stop-row').nth(1).click();
 assert.equal(await page.locator('#selection-title').isVisible(),true);
 assert(!/BASE#fin|Visita\|ñ/.test(await page.locator('#selection').innerText()));
 await page.locator('#close-selection').click();
 await page.locator('#open-plan-summary').click();
 assert(await page.locator('#plan-summary-dialog').isVisible());
 assert(!/witness_and_cardinality_bound|energy_gap_limit|Daniel|Lucas|Diego/.test(await page.locator('#plan-summary-dialog').innerText()));
 await page.screenshot({animations:'disabled',path:output+'/result-summary-dark.png'});
 note('Detalle y resumen preservan el resultado y usan terminaciones comprensibles, sin referencias al equipo.');
 await page.keyboard.press('Escape');
 await page.setViewportSize({width:390,height:844});
 await ready('/plan.html?tab=stops');
 await page.locator('#stops-tab').click();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({animations:'disabled',path:output+'/synthetic-plan-mobile.png'});
 note('Plan móvil conserva paradas y no desborda horizontalmente.');
}
assert.deepEqual(errors,[]);
note('Ninguna excepción JavaScript.');
await writeFile(output+'/browser-results.json',JSON.stringify({results,errors},null,2));
await browser.close();
